export function getProjectBySlug(slug: string) {
  return projects.find((p) => p.slug === slug);
}

export function getAdjacentProjects(slug: string) {
  const index = projects.findIndex((p) => p.slug === slug);
  if (index === -1) return { prev: undefined, next: undefined };
  const prev = projects[(index - 1 + projects.length) % projects.length];
  const next = projects[(index + 1) % projects.length];
  return { prev, next };
}

export type LocalizedProject = Project & { categoryLabel: string };

export function localizeProject(project: Project, lang: Locale): LocalizedProject {
  const isAr = lang === "ar";
  return {
    ...project,
    title: isAr ? project.titleAr : project.title,
    location: isAr ? project.locationAr : project.location,
    description: isAr ? project.descriptionAr : project.description,
    longDescription: isAr ? project.longDescriptionAr : project.longDescription,
    status: isAr ? project.statusAr : project.status,
    size: isAr ? project.sizeAr : project.size,
    beds: isAr ? project.bedsAr : project.beds,
    floor: isAr ? project.floorAr : project.floor,
    tags: isAr ? project.tagsAr : project.tags,
    keyFeatures: isAr ? project.keyFeaturesAr : project.keyFeatures,
    highlights: isAr ? project.highlightsAr : project.highlights,
    categoryLabel: isAr ? CATEGORY_LABELS[project.category].ar : CATEGORY_LABELS[project.category].en,
  };
}
